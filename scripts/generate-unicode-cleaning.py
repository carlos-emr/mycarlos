#!/usr/bin/env python3
"""Generates the one table of code points the AI helper's text cleaning uses
(#72 part B, threat model AI-01): the same ranges as a TypeScript module for
page code and as Rust constants for the native re-check, pinned to one Unicode
version (Python's unicodedata), not the webview's own.

    python3 -I scripts/generate-unicode-cleaning.py          # writes both files
    python3 -I scripts/generate-unicode-cleaning.py --check  # fails if stale

What the saved text does with each range (src/deidentify/textCleaning.ts):
- REMOVED: dropped. Default_Ignorable_Code_Point (DerivedCoreProperties, a
  derived property unicodedata does not expose, so the list is written here
  from the 15.0.0 file: soft hyphen, U+034F, variation selectors, tag
  characters, Hangul fillers, zero-width and bidirectional controls, ...).
- REPLACED: each run becomes one U+FFFD. Private use (Co), unassigned (Cn,
  noncharacters included) and surrogates (Cs); the preview marks and counts
  them (symbol fonts map visible signs to private-use code points).
- SPACES: folded to U+0020. Every Zs space but the space itself; tabs are kept.
- U+2028 and U+2029 (Zl, Zp) become a line break; written out in both outputs.

Rust refuses text that still holds a REMOVED or REPLACED code point, and
never edits the text; its copy of the table must equal this one
(src/deidentify/textCleaning.test.ts compares the two files).
"""

import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TS_OUT = ROOT / "src/deidentify/unicodeCleaningTable.ts"
RS_OUT = ROOT / "src-tauri/src/unicode_cleaning_table.rs"
VERSION = unicodedata.unidata_version
assert VERSION == "15.0.0", f"regenerate deliberately: unicodedata is {VERSION}"

# Default_Ignorable_Code_Point, DerivedCoreProperties-15.0.0.txt, merged.
DEFAULT_IGNORABLE = [
    (0x00AD, 0x00AD),
    (0x034F, 0x034F),
    (0x061C, 0x061C),
    (0x115F, 0x1160),
    (0x17B4, 0x17B5),
    (0x180B, 0x180F),
    (0x200B, 0x200F),
    (0x202A, 0x202E),
    (0x2060, 0x206F),
    (0x3164, 0x3164),
    (0xFE00, 0xFE0F),
    (0xFEFF, 0xFEFF),
    (0xFFA0, 0xFFA0),
    (0xFFF0, 0xFFF8),
    (0x1BCA0, 0x1BCA3),
    (0x1D173, 0x1D17A),
    (0xE0000, 0xE0FFF),
]


def in_ranges(ranges, cp):
    return any(lo <= cp <= hi for lo, hi in ranges)


def ranges_where(predicate):
    ranges = []
    start = None
    for cp in range(0x110000):
        if predicate(cp):
            if start is None:
                start = cp
        elif start is not None:
            ranges.append((start, cp - 1))
            start = None
    if start is not None:
        ranges.append((start, 0x10FFFF))
    return ranges


REPLACED = ranges_where(
    lambda cp: unicodedata.category(chr(cp)) in ("Co", "Cn", "Cs")
    and not in_ranges(DEFAULT_IGNORABLE, cp)
)
SPACES = ranges_where(lambda cp: unicodedata.category(chr(cp)) == "Zs" and cp != 0x20)
LINE_BREAKS = [(0x2028, 0x2029)]

HEADER = f"Generated by scripts/generate-unicode-cleaning.py from Unicode {VERSION}. Do not edit."


def ts_ranges(name, ranges, note):
    lines = [f"/** {note} */", f"export const {name}: readonly (readonly [number, number])[] = ["]
    for lo, hi in ranges:
        lines.append(f"  [0x{lo:04x}, 0x{hi:04x}],")
    lines.append("];")
    return "\n".join(lines)


def rs_ranges(name, ranges, note):
    # As rustfmt writes it: one range on one line, more on their own lines.
    if len(ranges) == 1:
        (lo, hi), = ranges
        return f"/// {note}\npub(crate) const {name}: &[(u32, u32)] = &[(0x{lo:04x}, 0x{hi:04x})];"
    lines = [f"/// {note}", f"pub(crate) const {name}: &[(u32, u32)] = &["]
    for lo, hi in ranges:
        lines.append(f"    (0x{lo:04x}, 0x{hi:04x}),")
    lines.append("];")
    return "\n".join(lines)


TS = "\n\n".join(
    [
        f"/* {HEADER} */",
        f'export const UNICODE_VERSION = "{VERSION}";',
        ts_ranges("REMOVED", DEFAULT_IGNORABLE, "Dropped from the saved text: Default_Ignorable_Code_Point."),
        ts_ranges("REPLACED", REPLACED, "Each run becomes one U+FFFD: private use, unassigned, surrogates."),
        ts_ranges("SPACES", SPACES, "Folded to U+0020: every other Zs space."),
        ts_ranges("LINE_BREAKS", LINE_BREAKS, "Folded to a line break: the line and paragraph separators."),
    ]
) + "\n"

RS = "\n\n".join(
    [
        f"//! {HEADER}",
        f'pub(crate) const UNICODE_VERSION: &str = "{VERSION}";',
        rs_ranges("REMOVED", DEFAULT_IGNORABLE, "Dropped from the saved text: Default_Ignorable_Code_Point."),
        rs_ranges("REPLACED", REPLACED, "Each run becomes one U+FFFD: private use, unassigned, surrogates."),
        rs_ranges("SPACES", SPACES, "Folded to U+0020: every other Zs space."),
        rs_ranges("LINE_BREAKS", LINE_BREAKS, "Folded to a line break: the line and paragraph separators."),
    ]
) + "\n"


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for path, content in ((TS_OUT, TS), (RS_OUT, RS)):
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("stale: " + ", ".join(stale), file=sys.stderr)
        sys.exit(1)
    print(f"Unicode {VERSION}: {len(DEFAULT_IGNORABLE)} removed, {len(REPLACED)} replaced, {len(SPACES)} space ranges")


if __name__ == "__main__":
    main()
